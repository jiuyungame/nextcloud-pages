_ANSI = re.compile(r"\x1b\[[0-9;]*[A-Za-z]")
#: ``file:line[:col]:`` anywhere in the line, not only at the start.
_LOCATION_ANY = re.compile(
    r"(?P<file>[A-Za-z0-9_][A-Za-z0-9_./\\-]*\.[A-Za-z0-9]{1,10}):(?P<line>\d+)(?::(?P<col>\d+))?:"
)
_LIQUID = re.compile(r"Liquid (?:Exception|syntax error)", re.IGNORECASE)
_LIQUID_LINE = re.compile(r"\(line\s+(\d+)\)")
_LIQUID_FILE = re.compile(r"\bin\s+([A-Za-z0-9_./\\-]+\.[A-Za-z0-9]{1,10})")
_VERSIONISH = re.compile(r"^[\d.]+$")
_ERROR_HINT = re.compile(
    r"(?i)\b(error|exception|failed|failure|cannot|unable|undefined|no such file|"
    r"permission denied|syntax error)\b|错误|失败|无法"
)


@dataclass
class BuildResult:
    build_id: int
    ok: bool
    ts: float
    ms: int
    exit_code: int
    command: list[str]
    output_dir: str
    output_files: int = 0
    installed: bool = False
    install_ms: int = 0
    timed_out: bool = False
    errors: list[dict] = field(default_factory=list)
    log_tail: str = ""

    def to_dict(self) -> dict:
        return {
            "build_id": self.build_id,
            "ok": self.ok,
            "ts": self.ts,
            "ms": self.ms,
            "exit_code": self.exit_code,
            "command": self.command,
            "output_dir": self.output_dir,
            "output_files": self.output_files,
            "installed": self.installed,
            "install_ms": self.install_ms,
            "timed_out": self.timed_out,
            "errors": self.errors[:30],
            "log_tail": self.log_tail,
        }


def _yaml_scalar(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    text = str(value)
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def write_overrides(site: Site, cfg: Config) -> Path | None:
    """Write ``recipe.overrides`` as YAML, outside the site directory."""
    # inside the site the file would be committed by git add -A and mirrored back
    if not site.recipe.overrides:
        return None
    lines = ["# generated by pages-bridge, do not edit", "---"]
    for key, value in site.recipe.overrides.items():
        lines.append(f"{key}: {_yaml_scalar(value)}")
    target = cfg.override_dir / f"{ARTIFACT_STEM}.yml"
    atomic_write_text(target, "\n".join(lines) + "\n")
    return target


def build_argv(site: Site, cfg: Config) -> list[str]:
    """Assemble the final build command; jekyll is the only preset there is."""
    if not site.recipe.command:
        return []
    argv = list(site.recipe.command)
    output = str(site.output_dir)

    # the generated overrides chain onto the site's own config file
    override = write_overrides(site, cfg)
    if override is not None and site.recipe.base_config:
        if "--config" not in argv:
            argv += ["--config", f"{site.recipe.base_config},{override}"]
    if "--destination" not in argv:
        argv += ["--destination", output]
    return argv


def _needs_install(site: Site) -> bool:
    """Whether dependencies must be installed; jekyll is the only generator, so bundler decides."""
    if not site.recipe.install_cmd:
        return False
    # let bundler itself report whether the gems are present
    try:
        proc = subprocess.run(
            ["bundle", "check"],
            cwd=str(site.preview),
            capture_output=True,
            text=True,
            timeout=90,
            # recipe.env is required here: without BUNDLE_PATH, bundle check inspects system gems
            env={
                **os.environ,
                "HOME": os.environ.get("HOME", "/root"),
                "LC_ALL": "C",
                **{k: str(v) for k, v in site.recipe.env.items()},
            },
            shell=False,
        )
        return proc.returncode != 0
    except (OSError, subprocess.TimeoutExpired):
        return True


def _run_capture(
    argv: list[str],
    cwd: Path,
    timeout: int,
    extra_env: dict[str, str] | None = None,
) -> tuple[int, str, bool]:
    """Run a command, return ``(exit code, merged output, timed out)``; a timeout kills the process group."""
    env = dict(os.environ)
    env.setdefault("HOME", "/root")
    env["LC_ALL"] = "C.UTF-8"
    env["JEKYLL_ENV"] = env.get("JEKYLL_ENV", "production")
    if extra_env:
        env.update({k: str(v) for k, v in extra_env.items()})

    proc = subprocess.Popen(
        argv,
        cwd=str(cwd),
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        errors="replace",
        env=env,
        shell=False,
        start_new_session=True,   # own process group, so a timeout can kill the whole tree
    )
    timed_out = False
    try:
        output, _ = proc.communicate(timeout=timeout)
    except subprocess.TimeoutExpired:
        timed_out = True
        _kill_group(proc)
        try:
            output, _ = proc.communicate(timeout=15)
        except subprocess.TimeoutExpired:
            _kill_group(proc, hard=True)
            output, _ = proc.communicate()
    return proc.returncode if not timed_out else -9, output or "", timed_out


def _kill_group(proc: subprocess.Popen, hard: bool = False) -> None:
    sig = signal.SIGKILL if hard else signal.SIGTERM
    try:
        os.killpg(os.getpgid(proc.pid), sig)
    except (ProcessLookupError, PermissionError):
        try:
            proc.kill()
        except OSError:
            pass


def extract_errors(log: str, limit: int = 50) -> list[dict]:
    """Heuristically pick useful error lines for the UI; the exit code and full log stay authoritative."""
    clean = _ANSI.sub("", log)
    found: list[dict] = []
    seen: set[str] = set()

    def push(item: dict) -> None:
        key = repr(sorted(item.items()))
        if key in seen:
            return
        seen.add(key)
        if len(found) < limit:
            found.append(item)

    for index, line in enumerate(clean.splitlines(), start=1):
        stripped = line.strip()
        if not stripped or len(stripped) > 400:
            continue

        loc = _LOCATION_ANY.search(line)
        if loc and _ERROR_HINT.search(stripped) and not _VERSIONISH.match(loc.group("file")):
            entry: dict = {
                "file": loc.group("file"),
                "line": int(loc.group("line")),
                "text": stripped,
            }
            if loc.group("col"):
                entry["column"] = int(loc.group("col"))
            push(entry)
            continue

        if _LIQUID.search(stripped):
            liquid: dict = {"text": stripped}
            line_match = _LIQUID_LINE.search(stripped)
            file_match = _LIQUID_FILE.search(stripped)
            if line_match:
                liquid["line"] = int(line_match.group(1))
            if file_match:
                liquid["file"] = file_match.group(1)
            if len(liquid) > 1:
                push(liquid)
                continue

        if _ERROR_HINT.search(stripped):
            push({"text": stripped, "log_line": index})
    return found


def _persist_log(
    cfg: Config, site: Site, build_id: int, argv: list[str],
    code: int, ok: bool, ms: int, files: int, log: str,
) -> None:
    """Persist the full output of one attempt."""
    # install failures land here too, otherwise the UI shows only exit=N with no log
    (cfg.log_dir / f"{ARTIFACT_STEM}.log").parent.mkdir(parents=True, exist_ok=True)
    atomic_write_text(
        cfg.log_dir / f"{ARTIFACT_STEM}.log",
        f"# build {build_id} @ {time.strftime('%Y-%m-%d %H:%M:%S', time.localtime())}\n"
        f"# cmd: {shlex.join(argv)}\n"
        f"# exit={code} ok={ok} ms={ms} files={files}\n\n{log}",
    )


def run_build(site: Site, cfg: Config, state: SiteState) -> BuildResult:
    """Build the **preview** tree; the commit tree is never built.

    ``site.preview`` is the directory every author's files are mirrored into, so the build input is
    the whole site and the preview can show an internal page. ``site.output_dir`` is inside that
    tree, which is what the preview route serves; nothing here reads or writes ``site.work``.
    """
    build_id = state.next_build_id
    started = time.monotonic()
    ts = time.time()

    site.preview.mkdir(parents=True, exist_ok=True)

    installed = False
    install_ms = 0
    if _needs_install(site):
        info("installing dependencies", cmd=shlex.join(site.recipe.install_cmd or []))
        t0 = time.monotonic()
        code, out, timed_out = _run_capture(
            list(site.recipe.install_cmd or []),
            cwd=site.preview,
            timeout=max(600, cfg.build_timeout_s * 3),
            # the install step needs recipe.env too, or bundler writes to a read-only system path
            extra_env=dict(site.recipe.env),
        )
        install_ms = int((time.monotonic() - t0) * 1000)
        installed = True
        if timed_out or code != 0:
            clean = _ANSI.sub("", out)
            result = BuildResult(
                build_id=build_id,
                ok=False,
                ts=ts,
                ms=int((time.monotonic() - started) * 1000),
                exit_code=code,
                command=list(site.recipe.install_cmd or []),
                output_dir=str(site.output_dir),
                installed=True,
                install_ms=install_ms,
                timed_out=timed_out,
                errors=extract_errors(out),
                log_tail=tail_lines(clean, cfg.log_tail_lines),
            )
            _persist_log(cfg, site, build_id, result.command, code, False, result.ms, 0, clean)
            state.record_build(result.to_dict())
            warn("dependency install failed", exit=code, timed_out=timed_out)
            return result

    argv = build_argv(site, cfg)
    if not argv:
        # no build command (an empty recipe.command): the mirrored preview tree is the artifact
        count = dir_file_count(site.preview, site.exclude)
        result = BuildResult(
            build_id=build_id,
            ok=True,
            ts=ts,
            ms=int((time.monotonic() - started) * 1000),
            exit_code=0,
            command=[],
            output_dir=str(site.output_dir),
            output_files=count,
            installed=installed,
            install_ms=install_ms,
        )
        state.record_build(result.to_dict())
        return result

    info("build started", build_id=build_id, cmd=shlex.join(argv))
    code, out, timed_out = _run_capture(
        argv,
        cwd=site.preview,
        timeout=cfg.build_timeout_s,
        extra_env=dict(site.recipe.env),
    )
    clean_log = _ANSI.sub("", out)
    ms = int((time.monotonic() - started) * 1000)

    if timed_out:
        warn("build timed out, process group killed", build_id=build_id, timeout=cfg.build_timeout_s)

    output_files = dir_file_count(site.output_dir, site.exclude) if site.output_dir.is_dir() else 0
    ok = (not timed_out) and code == 0

    result = BuildResult(
        build_id=build_id,
        ok=ok,
        ts=ts,
        ms=ms,
        exit_code=code,
        command=argv,
        output_dir=str(site.output_dir),
        output_files=output_files,
        installed=installed,
        install_ms=install_ms,
        timed_out=timed_out,
        errors=extract_errors(clean_log),
        log_tail=tail_lines(clean_log, cfg.log_tail_lines),
    )

    state.record_build(result.to_dict())
    (cfg.log_dir / f"{ARTIFACT_STEM}.log").parent.mkdir(parents=True, exist_ok=True)
    atomic_write_text(
        cfg.log_dir / f"{ARTIFACT_STEM}.log",
        f"# build {build_id} @ {time.strftime('%Y-%m-%d %H:%M:%S', time.localtime(ts))}\n"
        f"# cmd: {shlex.join(argv)}\n"
        f"# exit={code} ok={ok} ms={ms} files={output_files}\n\n{clean_log}",
    )
    info("build finished", build_id=build_id, ok=ok, exit=code, ms=ms, files=output_files)
    return result


def env_report(cfg: Config) -> dict:
    """Capability report: data source for ``occ pages:doctor`` and ``/env``.

    It also carries the app-facing part of the hosted configuration: the effective value of every
    parameter the app may push, where each one came from, and the fingerprints of the two secrets
    (never the plaintext, and never the full digest either).
    """
    import shutil

    tools = {}
    # what a jekyll build needs: git for the mirror/publish side, ruby/bundler/jekyll for the build
    for name in ("git", "ruby", "bundle", "jekyll"):
        path = shutil.which(name)
        version = None
        if path:
            try:
                proc = subprocess.run(
                    [name, "--version"],
                    capture_output=True,
                    text=True,
                    timeout=20,
                    env={**os.environ, "LC_ALL": "C"},
                    shell=False,
                )
                version = (proc.stdout or proc.stderr).strip().splitlines()[0][:120] if proc.stdout or proc.stderr else None
            except (OSError, subprocess.TimeoutExpired, IndexError):
                version = None
        tools[name] = {"path": path, "version": version}

    site = cfg.site
    site_report = None
    if site is not None:
        site_report = {
            "source": {
                "path": str(site.source),
                "exists": site.source.is_dir(),
                "readable": os.access(site.source, os.R_OK) if site.source.exists() else False,
            },
            "work": {
                "path": str(site.work),
                "exists": site.work.is_dir(),
                "writable": os.access(site.work, os.W_OK) if site.work.exists()
                else os.access(site.work.parent, os.W_OK) if site.work.parent.exists() else False,
            },
            # the tree the build runs in and the preview is served from; separate from the work copy
            "preview": {
                "path": str(site.preview),
                "exists": site.preview.is_dir(),
                "writable": os.access(site.preview, os.W_OK) if site.preview.exists()
                else os.access(site.preview.parent, os.W_OK) if site.preview.parent.exists() else False,
            },
            "output": str(site.output_dir),
            "recipe": site.recipe.to_dict(),
        }

    return {
        "ok": True,
        # the report is also built on a development machine (Windows has neither); null there
        "uid": os.getuid() if hasattr(os, "getuid") else None,
        "gid": os.getgid() if hasattr(os, "getgid") else None,
        "user": os.environ.get("USER") or os.environ.get("LOGNAME"),
        "home": os.environ.get("HOME"),
        "python": f"{os.sys.version_info.major}.{os.sys.version_info.minor}.{os.sys.version_info.micro}",
        # False while the bridge holds no usable secrets: everything but /health and /pair is 503
        "paired": cfg.paired,
        "nc_data_root": str(cfg.nc_data_root),
        "work_root": str(cfg.work_root),
        "tools": tools,
        # single site: one site object, not a list of sites (null until the app pushes one)
        "site": site_report,
        # what is in force, where each key came from ("app" / "toml" / "default"), fingerprints only
        "effective": effective_globals(cfg),
        "sources": global_sources(cfg),
        "secrets": {
            key: {"sha256_16": secret_fingerprint(getattr(cfg, key))} for key in SECRET_KEYS
        },
    }
