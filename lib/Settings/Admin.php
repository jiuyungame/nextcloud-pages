<?php

declare(strict_types=1);

namespace OCA\Pages\Settings;

use OCA\Pages\AppInfo\Application;
use OCA\Pages\Service\BridgeClient;
use OCA\Pages\Service\BridgeException;
use OCA\Pages\Service\ContentLock;
use OCA\Pages\Service\SiteRegistry;
use OCP\AppFramework\Http\TemplateResponse;
use OCP\IGroupManager;
use OCP\Server;
use OCP\Settings\ISettings;

/**
 * Pages panel in the admin settings.
 *
 * The page is deliberately small: only the values an administrator has to decide *for this instance*
 * to make the feature work - where the bridge is, how to authenticate (pairing), which folder of which
 * user holds the site, where it is published, and the two group grants. Everything else has a better
 * owner and stays out of the page:
 *
 *  - the global bridge parameters (timeouts, rate limits, delete-guard, listen address, …) belong to
 *    the bridge: its TOML file documents them, `occ pages:config get|set|list` sets them, and
 *    `occ pages:doctor` reports every effective value with its source;
 *  - the build recipe and the site-level exclude list are duplicates of the bridge's own configuration
 *    and are set through `PUT /api/site` (scripts) or the TOML, never typed here;
 *  - the two secrets are generated by pairing and replaced by the rotation button; the manual fallback is
 *    `occ config:app:set` (the storage is encrypted either way), so no plaintext secret input exists.
 *
 * The two fields that decide *where the site lives* (site storage user, site folder) are rendered
 * read-only once content exists; {@see ContentLock} owns that rule and the hint that explains it.
 * The author content directory stays editable - the bridge owns the shape check and the
 * confirm-on-existing question - and the reset in the danger zone is the way back.
 */
class Admin implements ISettings
{
    private ContentLock $lock;

    public function __construct(
        private SiteRegistry $registry,
        private BridgeClient $bridge,
        private IGroupManager $groupManager,
        ?ContentLock $lock = null,
    ) {
        // resolved lazily: a settings class is built from info.xml, and a page that cannot be constructed
        // is a page an administrator cannot use to fix anything
        $this->lock = $lock ?? Server::get(ContentLock::class);
    }

    /**
     * Builds the panel's view data: bridge health, the stored site and grants, the lock state of the
     * layout fields, and whether the publish repository exists (which locks remote and branch).
     */
    public function getForm(): TemplateResponse
    {
        // must be initialised here: the template also reads it when the health check is skipped
        $error = null;
        $health = null;
        if ($this->registry->isConnected()) {
            try {
                $health = $this->bridge->health();
            } catch (\Throwable $e) {
                $error = [
                    'code' => $e instanceof BridgeException ? $e->getBridgeCode() : 'ERROR',
                    'message' => $e->getMessage(),
                    'details' => $e instanceof BridgeException ? $e->getDetails() : [],
                    // the retry axis, so the notice can say whether the next refresh can help at all
                    'retryable' => $e instanceof BridgeException && $e->isRetryable(),
                ];
            }
        }
        // The publish repository exists = the site is initialised: the remote and the branch are then
        // locked. The bridge is the authority, but the page must not show the fields editable just
        // because it could not ask: the app's sticky flag answers instead, exactly like the save path
        // does (SiteController::initialised()), so a bridge that is down renders them locked too.
        $initialized = $this->registry->getSite() !== null && $this->registry->isRepoInitialised();
        if ($health !== null && $this->registry->getSite() !== null) {
            try {
                $initialized = ($this->bridge->siteStatus()['initialized'] ?? false) === true;
            } catch (\Throwable) {
                // the status call is an optimisation for the page; the API still enforces the lock
                $initialized = $this->registry->isRepoInitialised();
            }
        }

        return new TemplateResponse(Application::APP_ID, 'settings/admin', [
            'bridge_url' => $this->registry->getBridgeUrl(),
            'connected' => $this->registry->isConnected(),
            // the site storage user field's placeholder: an unset value has no sensible fallback
            'nc_user' => (string)($this->registry->getSite()['nc_user'] ?? ''),
            'shared_fingerprint' => $this->registry->secretFingerprint(SiteRegistry::KEY_SHARED_SECRET),
            'signing_fingerprint' => $this->registry->secretFingerprint(SiteRegistry::KEY_SIGNING_SECRET),
            // the one site of this instance (null until it is configured); the form edits it in place
            'site' => $this->registry->getSite(),
            // the two grants: who may review **and** publish (审核与发布, one permission), who may author,
            // and every group there is to pick from
            'review_groups' => $this->registry->getReviewGroups(),
            'author_root' => $this->registry->getAuthorRoot(),
            // the directory an article lands in when its author deleted it; the transfer never invents
            // it, so the form shows the stored value (default `Admin`)
            'orphanOwner' => $this->registry->getOrphanOwner(),
            'author_groups' => $this->registry->getAuthorGroups(),
            'all_groups' => $this->allGroups(),
            'protocol' => BridgeClient::PROTOCOL,
            'health' => $health,
            'health_error' => $error,
            // the two layout fields (storage user, folder) are read-only once content exists; the
            // template renders the disabled state and the one hint that says how to unlock them
            'locked' => $this->lock->isLocked(),
            'lock_hint' => $this->lock->message(),
            // the publish repository exists: the remote and the branch are locked until a reset
            'initialized' => $initialized,
        ], 'blank');
    }

    public function getSection(): string
    {
        return 'pages';
    }

    public function getPriority(): int
    {
        return 10;
    }

    /**
     * Every group of this instance, for the permission columns. Sorted by display name so that
     * the table does not follow the order of whichever group backend answers first.
     *
     * @return list<array{id:string,displayName:string}>
     */
    private function allGroups(): array
    {
        try {
            $groups = [];
            foreach ($this->groupManager->search('') as $group) {
                $gid = $group->getGID();
                // a backend may report an empty display name; the id is then the only readable label
                $displayName = trim((string)$group->getDisplayName());
                $groups[] = ['id' => $gid, 'displayName' => $displayName !== '' ? $displayName : $gid];
            }
        } catch (\Throwable) {
            // a broken group backend must not take the whole settings page down; the grant columns
            // then offer no group, which is visible and fixable, unlike a 500
            return [];
        }
        usort($groups, static fn (array $a, array $b): int => strcasecmp($a['displayName'], $b['displayName']));
        return $groups;
    }
}
