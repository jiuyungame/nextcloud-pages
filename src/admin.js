const url = (path) => generateUrl('/apps/pages' + path)

/** Bail out when this panel is not on the page (the script is loaded on every settings page) */
function currentPanel() {
	return document.getElementById('pages-settings')
}

function setFeedback(el, message, kind) {
	if (!el) {
		return
	}
	el.textContent = message
	el.className = 'pages-feedback' + (kind ? ' pages-feedback--' + kind : '')
}

/**
 * The groups granted one capability, as the array the API takes.
 *
 * The value lives in a hidden input per capability: the server renders the stored list into it, and
 * the picker writes every change back into it (see mountGrants). Reading the input instead of the
 * picker keeps this save path free of Vue — and a bundle whose pickers did not mount still saves the
 * values the server rendered, instead of sending nothing.
 *
 * An empty list is a value, not "unchanged": it keeps the documented default — authoring for every
 * signed-in user, reviewing and publishing for the administrators alone.
 *
 * @param {string} inputId the hidden input the capability's value is kept in
 * @returns {string[]}
 */
function grantGroups(inputId) {
	try {
		const value = JSON.parse(document.getElementById(inputId)?.value || '[]')
		return Array.isArray(value) ? value.map(String) : []
	} catch {
		// unreadable means "no grant stored here", which is the same default an empty list means
		return []
	}
}

/**
 * What `PUT /api/admin/config` takes from this page. Only the fields the page really shows are sent:
 * an absent key means "leave the stored value alone", which is exactly what the controls that live
 * elsewhere (the global parameters, the secrets) must read as.
 */
function collect() {
	const payload = {}
	const bridgeUrl = value('pages-bridge-url')
	if (bridgeUrl !== '') {
		payload.bridgeUrl = bridgeUrl
	}
	// The grants are lists, so "empty" is a real value ("no group is granted") and not "unchanged":
	// they are sent only when the permissions panel rendered on this page. Without the panel (older
	// template, or a page that never rendered it) both keys are omitted, which leaves the stored
	// grants untouched instead of silently clearing them.
	// The authoring list is the odd one of the two: empty means "every signed-in user", which is the
	// documented default, so an empty column is a value and not a revocation.
	if (document.getElementById('pages-permissions')) {
		payload.authorGroups = grantGroups('pages-author-groups')
		payload.reviewGroups = grantGroups('pages-review-groups')
	}
	// The author content directory is the only authoring setting in that section; who may author is
	// a permission column now (see above). It is sent as typed: the server validates the one-segment
	// shape and the reserved names, so a typo is a 400 with the rule, not a silent rewrite.
	if (document.getElementById('pages-authors')) {
		payload.authorRoot = value('pages-author-root')
	}
	return payload
}

/** After a successful save: the URL the server stored, the fingerprints, and the moved revision */
function applyResult(config) {
	const urlInput = document.getElementById('pages-bridge-url')
	if (urlInput && typeof config.bridge_url === 'string') {
		urlInput.value = config.bridge_url
	}
	const line = document.getElementById('pages-fingerprints')
	if (line && typeof config.shared_fingerprint === 'string') {
		const shared = config.shared_fingerprint || t('pages', '(not configured)')
		const signing = config.signing_fingerprint || t('pages', '(not configured)')
		line.textContent = t('pages', 'Shared secret') + ' ' + shared
			+ ' · ' + t('pages', 'Signing secret') + ' ' + signing
	}
	// the revision moved, so the two revision-based states are re-read from what the server returned
	const revision = typeof config.revision === 'number' ? config.revision : null
	if (revision !== null) {
		const panel = document.getElementById('pages-bridge-panel')
		const badge = document.getElementById('pages-sync-state')
		for (const el of [panel, badge]) {
			if (el) {
				el.dataset.revision = String(revision)
			}
		}
		if (badge && typeof config.has_unpushed === 'boolean') {
			badge.dataset.hasUnpushed = config.has_unpushed ? '1' : '0'
		}
		// the badge itself is refreshed from /api/bridge/health right after the push, so it is not
		// redrawn here from the revision alone (that would flash "unpushed" between the two calls)
	}
}

/**
 * The consistency state of the settings page, from the bridge's own report:
 *   - the stored revision is ahead of the last pushed one        → "Unpushed changes"
 *   - the bridge holds a different revision                      → "Out of sync - push again"
 *   - the bridge holds exactly the revision this app pushed       → "Synced"
 *
 * Only revisions are compared. The page no longer shows the global bridge parameters, so comparing
 * their field values here would compare nothing against the bridge's effective values and claim "out of
 * sync" for a page that cannot see them; that check moved to `occ pages:doctor` (the "bridge parameters"
 * row) and to `occ pages:config list`.
 *
 * @param {{config_revision?: number}|null} health the `/api/bridge/health` answer
 */
export function syncState(health) {
	const panel = document.getElementById('pages-bridge-panel')
	if (!panel) {
		return null
	}
	const revision = Number.parseInt(panel.dataset.revision || '0', 10)
	const pushed = Number.parseInt(panel.dataset.pushedRevision || '0', 10)
	// revision order: stored > pushed means this app has edits the bridge has never seen
	if (revision > pushed) {
		return 'unpushed'
	}
	const reported = Number(health?.config_revision)
	if (!Number.isFinite(reported)) {
		// no report from the bridge: there is nothing to compare, so the server-rendered state stands
		return null
	}
	return reported === revision ? 'synced' : 'out-of-sync'
}

/**
 * Renders the consistency badge from a fresh `/api/bridge/health` answer. The server already decided
 * the two revision-based states; this only upgrades them to "synced" or "out of sync" when the bridge
 * reported the revision it holds.
 */
function renderSyncState(state) {
	const badge = document.getElementById('pages-sync-state')
	if (!badge) {
		return
	}
	const mapping = {
		synced: { label: t('pages', 'Synced'), kind: 'ok' },
		unpushed: { label: t('pages', 'Unpushed changes'), kind: 'warn' },
		'out-of-sync': { label: t('pages', 'Out of sync - push again'), kind: 'error' },
	}
	const entry = state ? mapping[state] : null
	if (!entry) {
		// no report from the bridge: keep the server-rendered revision state
		if (badge.dataset.hasUnpushed === '1') {
			badge.textContent = t('pages', 'Changes not pushed to the bridge')
			badge.className = 'pages-badge warn'
		} else {
			badge.textContent = t('pages', 'In sync')
			badge.className = 'pages-badge ok'
		}
		return
	}
	badge.textContent = entry.label
	badge.className = 'pages-badge ' + entry.kind
}

const value = (id) => document.getElementById(id)?.value.trim() ?? ''

/**
 * The site storage user the form was rendered with. A save that changes it is a move of the source
 * between two users' files, which is the one edit that needs a preflight and, if the new location is
 * missing or empty, a deliberate choice (§14).
 */
const currentStorageUser = () => document.getElementById('pages-site-nc-user')?.dataset.current ?? ''
const storageUser = () => value('pages-site-nc-user')

/** The field value is the new stored value the moment the save went through */
function markStorageUser(id) {
	const input = document.getElementById('pages-site-nc-user')
	if (input && id) {
		input.dataset.current = id
	}
}

/** `bob` → `bob`, `/Sites/blog` → `bob:/Sites/blog`: one short label for the two locations */
const where = (user, path) => (user ? user : '?') + ':' + (path || '')

/** Bytes as KiB/MiB/GiB, the same rounding the backend uses for its own size messages */
function humanBytes(bytes) {
	let value = Number(bytes || 0)
	for (const unit of ['B', 'KiB', 'MiB', 'GiB']) {
		if (value < 1024 || unit === 'GiB') {
			return unit === 'B' ? value + 'B' : value.toFixed(1) + unit
		}
		value = value / 1024
	}
	return bytes + 'B'
}

/** Step keys → English labels (static keys: a dynamic t() call would not be extracted) */
const STEP_LABELS = {
	copy: 'copy',
	verify: 'verify',
	config: 'config',
	push: 'push',
	delete_old: 'delete the old copy',
}

/** The steps of a migration as a list; the failing one carries the reason */
function renderSteps(steps) {
	if (!Array.isArray(steps) || steps.length === 0) {
		return ''
	}
	return steps.map((step) => (step.ok ? '✓ ' : '✗ ')
		+ t('pages', STEP_LABELS[step.step] || step.step) + ' — ' + (step.message || '')).join(' · ')
}

/**
 * The live controls of the §14 panel. They are cloned out of the inert `<template>` the server renders,
 * so the page carries no migration input (and no radio group) while no migration is pending.
 */
const migrationPart = (name) => document.querySelector('#pages-site-migration [data-migration="' + name + '"]')

const siteElements = () => [
	document.getElementById('pages-site-save'),
	document.getElementById('pages-site-init'),
	document.getElementById('pages-site-pull'),
	migrationPart('start'),
	migrationPart('cancel'),
]

let siteFeedback = null
/** The quota verdict of the last preflight, together with the user it was asked for */
let migrationQuota = { user: '', ok: true }

function setSiteFeedback(message, kind) {
	setFeedback(siteFeedback, message, kind)
}

/**
 * Save and push, the "the new user wins" path: the target already holds a site, so nothing is copied
 * and the old location is left untouched. With no bridge paired yet the config is stored and the push
 * is skipped (the bridge is fed by "Save and push" later), so the answer says which of the two happened
 * instead of claiming a push that did not run.
 *
 * @returns {Promise<boolean>} whether the config reached the bridge as well
 */
async function saveSiteDirect(user, input) {
	await axios.put(url('/api/site'), input)
	markStorageUser(user)
	try {
		await axios.post(url('/api/bridge/push'))
		return true
	} catch {
		return false
	}
}

/** The one sentence both "saved" paths report, so they cannot drift apart */
const savedNote = (pushed) => pushed
	? t('pages', 'Saved and pushed to the bridge')
	: t('pages', 'Saved') + ' · ' + t('pages', 'Changes not pushed to the bridge')

/**
 * Preflight, then act on its `decision`. The two endpoint calls are the only new requests of this
 * flow; everything else is what the form already did.
 */
async function handleStorageUserChange(site, user) {
	const { data } = await axios.post(url('/api/admin/site/preflight'), { nc_user: user })
	const decision = data?.decision
	if (decision === 'save_directly') {
		const pushed = await saveSiteDirect(user, site)
		const path = data?.target?.path || ''
		setSiteFeedback(savedNote(pushed) + ' · '
			+ t('pages', 'The new location already had a folder and now wins; the old location is left untouched.')
			+ (path ? ' (' + where(data?.target_user, path) + ')' : ''), 'ok')
		return
	}
	if (decision === 'first_config') {
		const pushed = await saveSiteDirect(user, site)
		setSiteFeedback(savedNote(pushed) + ' · '
			+ t('pages', 'The current location does not exist yet; use "Initialise working copy (first git pull)".'), 'ok')
		return
	}
	// offer_migration: the move is a choice, never a side effect of saving (the source is not written)
	showMigration(data)
}

/** The §14 panel, materialised from the server's inert `<template>` the first time it is needed */
function ensureMigrationPanel() {
	const panel = document.getElementById('pages-site-migration')
	if (!panel) {
		return null
	}
	if (panel.childElementCount === 0) {
		const template = document.getElementById('pages-site-migration-template')
		if (!template || !template.content) {
			return null
		}
		panel.append(template.content.cloneNode(true))
	}
	return panel
}

function showMigration(preflight) {
	const panel = ensureMigrationPanel()
	if (!panel) {
		return
	}
	const warnings = migrationPart('warnings')
	const steps = migrationPart('steps')
	if (warnings) {
		const lines = Array.isArray(preflight?.warnings) ? [...preflight.warnings] : []
		warnings.hidden = lines.length === 0
		warnings.textContent = lines.join(' ')
	}
	if (steps) {
		steps.hidden = true
		steps.textContent = ''
	}
	const start = migrationPart('start')
	if (start) {
		start.disabled = preflight?.quota?.ok === false
	}
	migrationQuota = { user: String(preflight?.target_user || ''), ok: preflight?.quota?.ok !== false }
	const source = where(preflight?.source_user, preflight?.source?.path)
	const target = where(preflight?.target_user, preflight?.target?.path)
	const files = Number(preflight?.source?.files || 0)
	const size = Number(preflight?.source?.bytes || 0)
	const what = files > 0
		? t('pages', '%1$s files, %2$s', [files.toLocaleString(), humanBytes(size)])
		: t('pages', 'The new location is empty')
	setSiteFeedback(what + ' · ' + source + ' → ' + target, 'warn')
	panel.hidden = false
}

const chooseMigration = () => document.querySelector('input[name="pages-site-migration-mode"]:checked')?.value || 'migrate'

function hideMigration() {
	const panel = document.getElementById('pages-site-migration')
	if (panel) {
		panel.hidden = true
	}
}

async function runMigration(user) {
	const steps = migrationPart('steps')
	const { data } = await axios.post(url('/api/admin/site/migrate'), { nc_user: user })
	const lines = renderSteps(data?.steps)
	if (steps) {
		// the per-step report is the whole point of the endpoint: it stays on screen either way
		steps.hidden = lines === ''
		steps.textContent = lines
	}
	if (data?.ok) {
		markStorageUser(user)
		hideMigration()
		setSiteFeedback(t('pages', 'Migrated') + ' · ' + t('pages', 'Files, configuration and the bridge now use the new location.'), 'ok')
		return
	}
	setSiteFeedback(data?.quota
		? t('pages', 'The target user\'s quota is not enough. The old location is unchanged.')
		: (data?.message || t('pages', 'Migration failed')), 'error')
}

async function runGitRebuild(user, input) {
	const pushed = await saveSiteDirect(user, input)
	hideMigration()
	setSiteFeedback(savedNote(pushed) + ' · ' + t('pages', 'Rebuild from git: use "Initialise working copy (first git pull)" — the bridge clones and back-fills the folder.'), 'ok')
}

/**
 * The site form. One change beyond the plain save: a different "site storage user" is a move of the
 * source between two users' files, so it goes through preflight → choice → migrate (§14) instead of
 * being written straight away.
 */
function wireSite() {
	const save = document.getElementById('pages-site-save')
	if (!save) {
		return
	}
	const feedback = document.getElementById('pages-site-feedback')
	siteFeedback = feedback
	const init = document.getElementById('pages-site-init')
	const pull = document.getElementById('pages-site-pull')

	/** One busy frame for the whole flow: the panel's own buttons plus the §14 pair, if it exists */
	const migrationRun = async (label, work) => {
		for (const button of siteElements()) {
			if (button) {
				button.disabled = true
			}
		}
		setFeedback(feedback, label + '…')
		try {
			await work()
		} catch (error) {
			const message = error?.response?.data?.message || error?.message || t('pages', 'Failed')
			setFeedback(feedback, label + t('pages', 'Failed:') + message, 'error')
		} finally {
			for (const button of siteElements()) {
				if (button) {
					button.disabled = false
				}
			}
		}
	}

	save?.addEventListener('click', () => migrationRun(t('pages', 'Save site'), async () => {
		const site = collectSite()
		if (!site.nc_path) {
			setFeedback(feedback, t('pages', 'Missing site folder'), 'error')
			return
		}
		if (storageUser() !== currentStorageUser()) {
			const target = storageUser()
			await handleStorageUserChange(site, target)
			if (storageUser() !== target) {
				// the field changed again while the preflight was in flight: nothing was written
				setFeedback(feedback, t('pages', 'The site storage user changed again; save once more.'), 'warn')
			}
			return
		}
		if (!await saveSite()) {
			setFeedback(feedback, t('pages', 'Missing site folder'), 'error')
			return
		}
		// Stored in Nextcloud only: the bridge is fed by "Save and push", so say so instead of
		// claiming the config is already there (the status table shows the same thing)
		setFeedback(feedback, t('pages', 'Saved') + ' · ' + t('pages', 'Changes not pushed to the bridge'), 'ok')
	}))

	// the §14 buttons only exist while a migration is pending, so they are wired when they appear
	document.getElementById('pages-site-migration')?.addEventListener('click', (event) => {
		const target = event.target instanceof Element ? event.target.closest('[data-migration]') : null
		const part = target?.getAttribute('data-migration') || ''
		if (part === 'cancel') {
			hideMigration()
			setFeedback(feedback, t('pages', 'Cancelled') + ' · ' + t('pages', 'Nothing was changed.'), 'ok')
			return
		}
		if (part !== 'start') {
			return
		}
		const user = storageUser()
		if (user === '') {
			setFeedback(feedback, t('pages', 'Missing site folder'), 'error')
			return
		}
		const mode = chooseMigration()
		if (mode !== 'git' && !migrationQuota.ok && migrationQuota.user === user) {
			// the preflight already answered this, so no copy is started just to be rolled back
			setFeedback(feedback, t('pages', 'The target user\'s quota is not enough. The old location is unchanged.'), 'error')
			return
		}
		const label = mode === 'git' ? t('pages', 'Rebuilding from git') : t('pages', 'Migrating')
		migrationRun(label, () => (mode === 'git' ? runGitRebuild(user, collectSite()) : runMigration(user)))
	})

	init?.addEventListener('click', () => migrationRun(t('pages', 'Initialize work copy'), async () => {
		const { data } = await axios.post(url('/api/site/init'))
		const git = data?.result?.git?.action || '?'
		setFeedback(feedback, t('pages', 'Work copy is ready (') + git + ')', 'ok')
	}))

	pull?.addEventListener('click', () => migrationRun(t('pages', 'Pull from remote'), async () => {
		const { data } = await axios.post(url('/api/site/pull'))
		const changed = data?.result?.pull?.changed?.length ?? 0
		setFeedback(feedback, t('pages', 'Pulled, %s files changed', [String(changed)]), 'ok')
	}))
}

/**
 * Site form → site config object (snake_case keys shared with SiteRegistry / the bridge).
 * Single-site design: no `id`, no `name`, no `work_path` — the work copy is derived by the
 * bridge from its global work root, and the title is basename(nc_path).
 *
 * `recipe` and `exclude` are deliberately absent: they are the bridge's own configuration now, and an
 * omitted key keeps whatever is stored (the server preserves them rather than resetting them).
 */
function collectSite() {
	return {
		nc_user: value('pages-site-nc-user'),
		nc_path: value('pages-site-nc-path'),
		repo_url: value('pages-site-repo'),
		branch: value('pages-site-branch') || 'main',
	}
}

/**
 * Save the site into Nextcloud: there is exactly one site, so the object itself is the body
 * (no id in the URL, no `name`, no `work_path`). "Save and push" runs this first, so what reaches
 * the bridge is exactly what the administrator just typed.
 * @returns {Promise<boolean>} false when there is nothing to save
 */
export async function saveSite() {
	const site = collectSite()
	if (!site.nc_path) {
		return false
	}
	await axios.put(url('/api/site'), site)
	return true
}

/** Refresh the fingerprint line after a rotation: still fingerprints, never plaintext */
function applyFingerprints(fingerprints) {
	const line = document.getElementById('pages-fingerprints')
	if (!line) {
		return
	}
	const shared = fingerprints.shared_secret || t('pages', '(not configured)')
	const signing = fingerprints.session_signing_secret || t('pages', '(not configured)')
	line.textContent = t('pages', 'Shared secret') + ' ' + shared
		+ ' · ' + t('pages', 'Signing secret') + ' ' + signing
}

/**
 * The bridge panel: pair while unpaired, then "save and push" / "rotate secrets" / "pair again".
 * It reloads itself once the pairing state changes, because the two states are different forms and
 * the server renders the right one — a reload is cheaper and less error-prone than rebuilding it.
 */
function wireBridge() {
	const panel = document.getElementById('pages-bridge-panel')
	if (!panel) {
		return
	}
	const feedback = document.getElementById('pages-feedback')
	const restartNote = document.getElementById('pages-restart-note')
	const paired = panel.dataset.paired === '1'

	/** The bridge tells us whether a restart is needed (only `listen` does); show it as a note */
	const showRestart = (needed) => {
		if (!restartNote) {
			return
		}
		restartNote.hidden = !needed
		restartNote.textContent = needed ? t('pages', 'Restart the bridge for this change to take effect.') : ''
	}

	/** A failed bridge call: prefer the specific code the bridge sent over a generic message */
	const reportError = (error, fallback) => {
		const data = error?.response?.data ?? {}
		let message = data.message || error?.message || t('pages', fallback)
		if (data.error_code === 'BAD_CODE' && typeof data.attemptsLeft === 'number') {
			message += ' · ' + t('pages', '%s attempts left', [String(data.attemptsLeft)])
		}
		if (data.error_code === 'ALREADY_PAIRED') {
			// the code was valid, but the bridge already holds a different pair: a re-run of
			// install.sh does not help, the bridge state has to be dropped first
			message += ' · ' + t('pages', 'The bridge is paired with another Nextcloud; clear its state and pair again.')
		}
		if (error?.response?.status === 503) {
			// the one retryable failure: nothing was decided, so the next click can simply work
			message += ' · ' + t('pages', 'The bridge did not answer; it may be starting. Try again in a moment.')
		}
		setFeedback(feedback, message, 'error')
	}

	if (!paired) {
		const pairButton = document.getElementById('pages-pair')
		const codeInput = document.getElementById('pages-pair-code')
		pairButton?.addEventListener('click', async () => {
			const bridgeUrl = value('pages-bridge-url')
			const code = value('pages-pair-code')
			if (!bridgeUrl || !code) {
				setFeedback(feedback, t('pages', 'Missing bridge URL or pairing code'), 'error')
				return
			}
			pairButton.disabled = true
			setFeedback(feedback, t('pages', 'Pairing…'))
			try {
				const { data } = await axios.post(url('/api/bridge/pair'), { url: bridgeUrl, code })
				setFeedback(feedback, t('pages', 'Paired') + ' · ' + t('pages', 'protocol v') + data.protocol, 'ok')
				// the server decides which panel to render, so ask it for the paired one
				window.setTimeout(() => window.location.reload(), 1200)
			} catch (error) {
				reportError(error, 'Pairing failed')
			} finally {
				pairButton.disabled = false
			}
		})
		// Enter in the code field pairs, which is what the install output invites you to do
		codeInput?.addEventListener('keydown', (event) => {
			if (event.key === 'Enter') {
				event.preventDefault()
				pairButton?.click()
			}
		})
		return
	}

	const save = document.getElementById('pages-save')
	const rotate = document.getElementById('pages-rotate')
	const pairAgain = document.getElementById('pages-pair-again')

	/**
	 * Store the form, hand it to the bridge, then re-read the state. Extra options carry a rotation.
	 * @returns {Promise<boolean>} false when the bridge refused the push
	 */
	const saveAndPush = async (options = {}) => {
		// the site form is part of what is pushed, so it is stored first (and the server answers 412
		// when there is nothing to push); `Missing site folder` then means "no folder on this page"
		if (!await saveSite()) {
			setFeedback(feedback, t('pages', 'Missing site folder'), 'error')
			return false
		}
		const { data: saved } = await axios.put(url('/api/admin/config'), collect())
		// the write answer carries the new revision next to the config, so the badge can move at once
		applyResult({ ...(saved?.config ?? {}), revision: saved?.revision, has_unpushed: saved?.has_unpushed })
		const body = options.rotate ? { rotate: true } : {}
		const { data } = await axios.post(url('/api/bridge/push'), body)
		const fingerprints = data?.fingerprints
		if (fingerprints) {
			applyFingerprints(fingerprints)
		}
		showRestart(Boolean(data?.restart_required))
		await refreshState()
		return true
	}

	const withButtons = async (busy, work) => {
		for (const button of [save, rotate, pairAgain]) {
			if (button) {
				button.disabled = true
			}
		}
		setFeedback(feedback, busy)
		try {
			await work()
			return true
		} catch (error) {
			reportError(error, 'Failed')
			return false
		} finally {
			for (const button of [save, rotate, pairAgain]) {
				if (button) {
					button.disabled = false
				}
			}
		}
	}

	save?.addEventListener('click', () => withButtons(t('pages', 'Pushing…'), async () => {
		if (await saveAndPush()) {
			setFeedback(feedback, t('pages', 'Saved and pushed to the bridge'), 'ok')
		}
	}))

	rotate?.addEventListener('click', () => withButtons(t('pages', 'Pushing…'), async () => {
		if (!window.confirm(t('pages', 'Replace both secrets with new ones? The bridge is updated in the same request.'))) {
			setFeedback(feedback, '')
			return
		}
		if (await saveAndPush({ rotate: true })) {
			setFeedback(feedback, t('pages', 'Secrets rotated and pushed'), 'ok')
		}
	}))

	pairAgain?.addEventListener('click', () => withButtons(t('pages', 'Pairing…'), async () => {
		if (!window.confirm(t('pages', 'Pair again? This needs a new pairing code from bridge/install.sh.'))) {
			setFeedback(feedback, '')
			return
		}
		// keep the URL; the secrets are discarded by the bridge when the new pair is written
		const bridgeUrl = value('pages-bridge-url')
		const code = window.prompt(t('pages', 'Pairing code'), '')
		if (!bridgeUrl || !code) {
			setFeedback(feedback, t('pages', 'Missing bridge URL or pairing code'), 'error')
			return
		}
		const { data } = await axios.post(url('/api/bridge/pair'), { url: bridgeUrl, code })
		setFeedback(feedback, t('pages', 'Paired') + ' · ' + t('pages', 'protocol v') + data.protocol, 'ok')
		window.setTimeout(() => window.location.reload(), 1200)
	}))
}

/**
 * Reads `/api/bridge/health` and renders the consistency badge from the revision it reports. Runs on
 * load and after every push, so the two states are never computed from a stale page.
 */
async function refreshState() {
	try {
		const { data } = await axios.get(url('/api/bridge/health'))
		renderSyncState(syncState(data?.health ?? null))
	} catch {
		// the health route is read-only and failure-tolerant; a broken answer must not break the form
	}
}

/**
 * Writes one capability's list into the hidden input the save path reads.
 *
 * @param {string} inputId the capability's hidden input
 * @param {string[]} value the group ids to keep
 */
function writeGrantValue(inputId, value) {
	const input = document.getElementById(inputId)
	if (input) {
		input.value = JSON.stringify(Array.isArray(value) ? value : [])
	}
}

/**
 * The capability pickers (src/GrantPicker.vue) mounted into #pages-grants.
 *
 * The server renders the grants twice: into the hidden inputs (what collect() saves) and into the
 * JSON block the pickers start from. That repetition is the fallback — a picker that never mounts
 * leaves the hidden inputs carrying what the server rendered, so the form saves the stored grants
 * instead of clearing them.
 */
function mountGrants() {
	const host = document.getElementById('pages-grants')
	if (!host) {
		return
	}
	let state
	try {
		state = JSON.parse(document.getElementById('pages-grants-state')?.textContent || '{}')
	} catch {
		// unreadable state: nothing to hand to the pickers, the hidden inputs stay as rendered
		return
	}
	const options = Array.isArray(state?.options) ? state.options : []
	/*
	 * The rows are reactive on purpose: NcSelect is controlled through modelValue, so the list it
	 * emits has to come back down as the new prop — otherwise the tag it just added would disappear
	 * again on the next render.
	 */
	const rows = reactive((Array.isArray(state?.grants) ? state.grants : []).map((grant) => ({
		id: String(grant?.id || ''),
		label: String(grant?.label || ''),
		placeholder: String(grant?.placeholder || ''),
		value: Array.isArray(grant?.value) ? grant.value.map(String) : [],
	})).filter((row) => row.id !== ''))
	if (rows.length === 0) {
		return
	}

	try {
		createApp({
			name: 'PagesGrants',
			setup() {
				return () => h('div', { class: 'pages-grants__rows' }, rows.map((row) => h(GrantPicker, {
					key: row.id,
					label: row.label,
					options,
					placeholder: row.placeholder,
					modelValue: row.value,
					'onUpdate:modelValue': (value) => {
						row.value = value
						writeGrantValue(row.id, value)
					},
				})))
			},
		}).mount(host)
	} catch (error) {
		// the pickers are a convenience; the hidden inputs keep the save path working without them
		console.error('Pages: the permission pickers did not mount; saving the rendered grants.', error)
	}
}

function wire() {
	const panel = currentPanel()
	if (!panel) {
		return
	}
	mountGrants()
	wireSite()
	wireBridge()
	// the revision the bridge holds comes from the bridge, so it is refreshed on load
	refreshState()
}

if (document.readyState === 'loading') {
	document.addEventListener('DOMContentLoaded', wire)
} else {
	wire()
}
