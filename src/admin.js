/**
 * Admin settings panel: plain DOM + @nextcloud/axios, with Vue only for the grant pickers
 * (src/GrantPicker.vue). The PHP template renders the current values, this script handles
 * "save → submit → feedback" — including keeping the hidden inputs the save path reads in step with
 * the pickers.
 *
 * The page has 9 controls, and this script only touches those: the bridge URL, the pairing code (while
 * unpaired), the four site fields, the author content directory, and the two grant pickers. The global
 * bridge parameters are not on the page any more (bridge TOML / `occ pages:config`), the build recipe and
 * the site-level excludes are the bridge's own (the save path keeps whatever is stored), and the two
 * secrets are generated by pairing and rotated by a button — so no code here reads or writes a
 * plaintext secret.
 *
 * Built as the IIFE js/pages-admin.js (second Vite entry).
 */
