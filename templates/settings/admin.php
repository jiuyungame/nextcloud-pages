<?php
/**
 * Admin settings → Pages.
 *
 * Four blocks and a danger zone, nothing else:
 *
 *   ① Connection  the bridge URL (saved automatically), pairing while unpaired, the live status line
 *                  of a paired bridge, and the two secret actions (rotate / pair again).
 *   ② Site        the four fields that describe where the site lives. They are written through: leaving
 *                  any of them saves the whole block and pushes it to the bridge in one call, and a
 *                  bridge that refuses leaves every field at its previous value. Below them the three
 *                  data operations (Apply source / Import, and the one Create-or-Pull button) and a
 *                  facts-only summary.
 *   ③ Authors     the author content directory and the orphan owner directory (the folder that
 *                  receives an article whose author deleted it), written through the same way.
 *   ④ Permissions the two group grants; a change is saved immediately.
 *
 * The danger zone at the bottom is the only destructive action: it clears this app's bookkeeping and
 * the bridge's copies, and it is the only way to unlock the three layout fields (see ContentLock).
 *
 * Everything else has a better owner and is only *referenced* here, never edited:
 *   - the global bridge parameters (16 keys) live in the bridge TOML and `occ pages:config`; the
 *     doctor reports every effective value with its source;
 *   - the build recipe and the site-level exclude list are duplicates of bridge configuration;
 *   - the two secrets are generated by pairing or rotation; only fingerprints are ever shown.
 *
 * @var array $_
 * @var \OCP\IL10N $l
 */

use OCP\Util;

// the admin bundle is built separately from the app main bundle
Util::addStyle('pages', 'pages-admin');
Util::addScript('pages', 'pages-admin');

$health = $_['health'] ?? null;
$error = $_['health_error'] ?? null;
$connected = (bool)$_['connected'];
$site = is_array($_['site'] ?? null) ? $_['site'] : [];
$version = (string)($health['version'] ?? '');
$hasRemote = trim((string)($site['repo_url'] ?? '')) !== '';
$locked = (bool)($_['locked'] ?? false);
$lockHint = (string)($_['lock_hint'] ?? '');
// the two fields that name content (the site storage user and the site folder): a disabled input is
// the only rendering a browser cannot edit
$layoutDisabled = $locked ? ' disabled="disabled"' : '';
// the publish repository exists: the remote and the branch are locked until a reset deletes it
$initialized = (bool)($_['initialized'] ?? false);
$remoteDisabled = $initialized ? ' disabled="disabled"' : '';
$authorRoot = (string)($_['author_root'] ?? 'tmp');
// the directory an article lands in when its author deleted it; the backend validates the name
$orphanOwner = (string)($_['orphanOwner'] ?? 'Admin');
$protocol = (string)$_['protocol'];
?>
<div class="section" id="pages-settings" data-locked="<?php p($locked ? '1' : '0'); ?>">
	<h2>Pages</h2>
	<p class="settings-hint">
		<?php p($l->t('Edit static site sources in Nextcloud; after saving, pages-bridge on the host mirrors, builds and pushes them to the git remote.')); ?>
	</p>

	<h3><?php p('① ' . $l->t('Connection')); ?></h3>
	<?php // the state comes from the server, so the panel is right on first paint (no flash of the wrong form) ?>
	<div id="pages-bridge-panel" data-paired="<?php p($connected ? '1' : '0'); ?>">
		<p>
			<label for="pages-bridge-url"><?php p($l->t('URL')); ?></label><br />
			<input type="text" id="pages-bridge-url" placeholder="http://127.0.0.1:8787"
				value="<?php p($_['bridge_url']); ?>" style="width: 320px;" />
			<span class="settings-hint"><?php p($l->t('Saved automatically.')); ?></span>
		</p>

		<?php if (!$connected): ?>
			<p id="pages-pair-row">
				<label for="pages-pair-code"><?php p($l->t('Pairing code')); ?></label><br />
				<input type="text" id="pages-pair-code" autocomplete="off" placeholder="XXXXXXXX" style="width: 160px;" />
				<button type="button" id="pages-pair" class="primary"><?php p($l->t('Pair')); ?></button>
			</p>
			<p class="settings-hint">
				<?php p($l->t('Run `sudo bridge/install.sh` on the Nextcloud host: it prints the pairing code (valid for 10 minutes, 3 tries). Hosted pairing only works when the bridge runs on the same machine.')); ?>
			</p>
		<?php else: ?>
			<p id="pages-bridge-status" class="settings-hint">
				<?php if ($error !== null): ?>
					<span class="pages-badge error"><?php p($l->t('Unreachable')); ?></span>
					<code><?php p(($error['code'] ?? '') . ' — ' . ($error['message'] ?? '')); ?></code>
					<?php if (($error['retryable'] ?? false) === true): ?>
						<br /><?php p($l->t('The service did not answer, so nothing was changed: start it and reload this page.')); ?>
					<?php endif; ?>
				<?php else: ?>
					<span class="pages-badge ok"><?php p($l->t('Connected')); ?></span>
					<?php
				        // "Connected · protocol v3 · bridge 1.3.0" - the three facts of the connection
				        $parts = [$l->t('protocol v') . $protocol];
				        if ($version !== '') {
				            $parts[] = $l->t('bridge') . ' ' . $version;
				        }
				        p(' · ' . implode(' · ', $parts));
				        ?>
				<?php endif; ?>
			</p>
			<p>
				<button type="button" id="pages-rotate"><?php p($l->t('Rotate secrets')); ?></button>
				<button type="button" id="pages-pair-again"><?php p($l->t('Pair again')); ?></button>
			</p>
		<?php endif; ?>

		<p class="settings-hint" id="pages-fingerprints">
			<?php p($l->t('Shared secret') . ' ' . ($_['shared_fingerprint'] !== '' ? $_['shared_fingerprint'] : $l->t('(not configured)'))); ?>
			·
			<?php p($l->t('Signing secret') . ' ' . ($_['signing_fingerprint'] !== '' ? $_['signing_fingerprint'] : $l->t('(not configured)'))); ?>
			<br />
			<?php p($l->t('The app generates both secrets while pairing and stores them encrypted; only fingerprints are ever shown here. The manual fallback is `occ config:app:set`.')); ?>
		</p>
	</div>

	<h3><?php p('② ' . $l->t('Site')); ?></h3>
	<p class="settings-hint" id="pages-site-hint">
		<?php p($l->t('Leaving any of these four fields saves all of them and pushes them to the bridge; a value the bridge refuses leaves every field as it was.')); ?>
	</p>
	<?php if ($locked): ?>
		<p class="settings-hint" id="pages-site-lock-hint"><?php p($lockHint); ?></p>
	<?php endif; ?>
	<?php // no site id and no name any more: the title is basename(nc_path), derived by the backend ?>
	<div id="pages-site" data-initialized="<?php p($initialized ? '1' : '0'); ?>">
		<p>
			<label for="pages-site-nc-user"><?php p($l->t('Site storage user')); ?></label><br />
			<input type="text" id="pages-site-nc-user" placeholder="<?php p((string)($_['nc_user'] ?? '')); ?>"
				value="<?php p($site['nc_user'] ?? ''); ?>" style="width: 200px;"<?php p($layoutDisabled); ?> />
			<span class="settings-hint"><?php p($l->t('Leave empty to use the current administrator.')); ?></span>
		</p>
		<p>
			<label for="pages-site-nc-path"><?php p($l->t('Nextcloud folder (source of truth)')); ?></label><br />
			<input type="text" id="pages-site-nc-path" placeholder="/Sites/my-site"
				value="<?php p($site['nc_path'] ?? ''); ?>" style="width: 320px;"<?php p($layoutDisabled); ?> />
			<span class="settings-hint"><?php p($l->t('Files-app edits do not rebuild the preview automatically: use Apply source.')); ?></span>
		</p>
		<p>
			<label for="pages-site-repo"><?php p($l->t('Git remote (optional)')); ?></label><br />
			<input type="text" id="pages-site-repo" placeholder="git@github.com:user/repo.git"
				value="<?php p($site['repo_url'] ?? ''); ?>" style="width: 420px;"<?php p($remoteDisabled); ?> />
			<span class="settings-hint"><?php p($l->t('Leave it empty to publish without a remote: a publish is the commit itself.')); ?></span>
		</p>
		<p>
			<label for="pages-site-branch"><?php p($l->t('Branch')); ?></label><br />
			<input type="text" id="pages-site-branch" placeholder="main"
				value="<?php p($site['branch'] ?? 'main'); ?>" style="width: 160px;"<?php p($remoteDisabled); ?> />
		</p>
		<?php if ($initialized): ?>
			<p class="settings-hint" id="pages-remote-lock-hint"><?php p($l->t('Locked: initialised. Reset Pages to change this.')); ?></p>
		<?php endif; ?>
	</div>

	<p>
		<button type="button" id="pages-site-apply" class="primary"><?php p($l->t('Apply source')); ?></button>
		<?php if (!$initialized || $hasRemote): ?>
			<?php
            // ONE button for the pair: it creates the local repository when no remote is filled and
            // pulls the remote's content when one is. Once the repository is initialised without a
            // remote there is nothing to create and nothing to pull, so it is not rendered at all;
            // reset (which deletes the trees) is the only way to bring it back.
            ?>
			<button type="button" id="pages-site-sync"><?php p($hasRemote ? $l->t('Pull') : $l->t('Create')); ?></button>
		<?php endif; ?>
	</p>
	<?php
    // Import: a zip/tgz replaces the folder whole. The question is asked before the upload, so a click
    // that only meant to inspect a file cannot empty the folder.
    ?>
	<p>
		<input type="file" id="pages-site-import-file" accept=".zip,.tar.gz,.tgz,application/zip,application/gzip" />
		<button type="button" id="pages-site-import"><?php p($l->t('Import source…')); ?></button>
		<span class="settings-hint"><?php p($l->t('A zip or tar.gz replaces the whole folder: it is backed up first, then emptied and written from the archive. The archive needs a _config.yml at its top level (or inside its single top-level folder).')); ?></span>
	</p>
	<p class="settings-hint" id="pages-site-summary">
		<?php p($l->t('HEAD')); ?>
		<code id="pages-site-head">—</code>
		·
		<?php p($l->t('Remote ahead')); ?>
		<code id="pages-site-ahead">—</code>
	</p>

	<?php
    // Authoring: every participating user writes into their own `Pages/` folder, whose whole tree the
    // app mirrors into the one site under `<author content directory>/<user>/`. The directory is one
    // site-relative path segment, never empty (default `tmp`).
    ?>
	<h3><?php p('③ ' . $l->t('Authors')); ?></h3>
	<p class="settings-hint">
		<?php p($l->t('Everyone with the authoring grant writes into the Pages folder of their own files. The site receives everything in it under <content directory>/<user>/, and every file — pages and images alike — has to pass review before the site serves it.')); ?>
	</p>
	<div id="pages-authors">
		<p>
			<?php // always editable, also with content registered: the bridge decides whether the move is acceptable (409 CONFIRM_REQUIRED on an existing folder) ?>
			<label for="pages-author-root"><?php p($l->t('Author content directory')); ?></label><br />
			<input type="text" id="pages-author-root" value="<?php p($authorRoot); ?>"
				placeholder="tmp" style="width: 320px;" />
			<span class="settings-hint"><?php p($l->t('One folder name inside the site (letters, digits, dot, underscore, hyphen), never empty. Default: tmp.')); ?></span>
		</p>
		<p>
			<?php
		    // The directory that receives an article whose author deleted it (转交孤儿所有者): the file is
		    // written into the site source under `<author_root>/<orphanOwner>/…` and becomes the site's
		    // own, so this name must not be a real user - real uids are excluded from the mirror.
		    ?>
			<label for="pages-orphan-owner"><?php p($l->t('Orphan owner directory')); ?></label><br />
			<input type="text" id="pages-orphan-owner" value="<?php p($orphanOwner); ?>"
				placeholder="Admin" style="width: 320px;" />
			<span class="settings-hint"><?php p($l->t('The directory that receives articles whose author deleted them (must not be an existing user).')); ?></span>
		</p>
	</div>

	<?php
    // Two capabilities, each a group list; administrators always hold both, and the preview needs no
    // grant at all (every signed-in user may open it). Reviewing and publishing are ONE permission
    // since the merge (审核与发布): deciding about a request and pushing the commit are the same job,
    // so there is one picker for both - the retired publish grant is merged into it by the migration
    // and is not shown any more.
    $authorGroups = array_map('strval', is_array($_['author_groups'] ?? null) ? $_['author_groups'] : []);
    $reviewGroups = array_map('strval', is_array($_['review_groups'] ?? null) ? $_['review_groups'] : []);
    $allGroups = is_array($_['all_groups'] ?? null) ? $_['all_groups'] : [];
    // One option list for the two pickers; an entry without an id cannot be granted, so it is dropped
    $grantOptions = [];
    foreach ($allGroups as $group) {
        $gid = (string)($group['id'] ?? '');
        if ($gid === '') {
            continue;
        }
        $grantOptions[] = ['id' => $gid, 'displayName' => (string)($group['displayName'] ?? $gid)];
    }
    ?>
	<h3><?php p('④ ' . $l->t('Permissions')); ?></h3>
	<p class="settings-hint"><?php p($l->t('Administrators always have full access. Grant more here.')); ?></p>
	<p class="settings-hint"><?php p($l->t('All signed-in users can view the preview.')); ?></p>
	<div id="pages-permissions">
		<?php
        // One picker per capability, rendered by src/GrantPicker.vue into the container below. An
        // empty list keeps the documented default: authoring is open to every signed-in user, the
        // review-and-publish grant stays with the administrators alone. The label of the second one
        // says that it covers publishing, because it does.
        $grants = [
            ['pages-author-groups', $l->t('Author'), $authorGroups, $l->t('every signed-in user')],
            ['pages-review-groups', $l->t('Review and publish'), $reviewGroups, $l->t('administrators only')],
        ];
        $grantState = ['options' => $grantOptions, 'grants' => []];
        foreach ($grants as [$grantId, $grantLabel, $grantValue, $emptyLabel]) {
            $grantState['grants'][] = [
                'id' => $grantId,
                'label' => $grantLabel,
                'placeholder' => $emptyLabel,
                'value' => array_values($grantValue),
            ];
        }
        // the pickers start from this; JSON_HEX_* keeps a group name from closing the script tag
        $grantJson = json_encode($grantState, JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT | JSON_UNESCAPED_UNICODE);
        if ($grantJson === false) {
            $grantJson = '{"options":[],"grants":[]}';
        }
        ?>
		<div id="pages-grants"></div>
		<?php // The values, in the inputs the plain save path reads (src/admin.js). They are rendered
		      // by the server, so a bundle whose pickers never mount still saves what is stored now. ?>
		<?php foreach ($grantState['grants'] as $grant): ?>
			<?php $grantInputValue = json_encode($grant['value'], JSON_UNESCAPED_UNICODE); ?>
			<input type="hidden" class="pages-grant-value" id="<?php p((string)$grant['id']); ?>"
				value="<?php p(is_string($grantInputValue) ? $grantInputValue : '[]'); ?>" />
		<?php endforeach; ?>
		<script type="application/json" id="pages-grants-state"><?php print_unescaped($grantJson); ?></script>
		<p class="settings-hint"><?php p($l->t('Each capability is independent. Search for a group and select as many as the capability should have; remove a tag to take that grant away. Every change is saved immediately.')); ?></p>
		<p class="settings-hint"><?php p($l->t('“Review and publish” is one permission: deciding about a visibility request and pushing the commit are the same job.')); ?></p>
	</div>

	<h3><?php p($l->t('Danger zone')); ?></h3>
	<p class="settings-hint">
		<?php p($l->t('Reset Pages clears both sides of the configuration: the app loses its manifest, its cache tables, the site settings and the pairing, and the bridge deletes its work and preview copies outright. Only the app side is backed up first; the bridge copies are rebuilt from your files. Your files are never touched: the site folder and every author\'s Pages folder stay exactly as they are.')); ?>
	</p>
	<p>
		<button type="button" id="pages-reset" class="pages-danger">
			<?php p($l->t('Reset Pages (back to a fresh install)')); ?>
		</button>
	</p>

	<?php // the dialogs and toasts of this page are Vue components; the script mounts them here ?>
	<div id="pages-settings-ui"></div>
</div>
