<?php
/**
 * Admin settings → Pages.
 *
 * The page holds 9 editable controls and nothing else. What an administrator must decide for this
 * instance is: where the bridge is, how to authenticate (one-time pairing code + Pair), which user's
 * folder holds the site and where it is published (4 fields), the author content directory, and the two
 * group grants (the pickers). Everything else has a better owner and is *summarised* here, never edited:
 *
 *   - the global bridge parameters (16 keys: timeouts, debounce, delete guard, paths, listen address,
 *     exclusions…) live in the bridge TOML and in `occ pages:config get|set|list`; the Status table shows
 *     the summary and `occ pages:doctor --json` every effective value with its source;
 *   - the build recipe (output dir, build command, install command) and the site-level exclude list are
 *     duplicates of bridge configuration: `PUT /api/site` accepts them for scripts, the page does not
 *     type them;
 *   - the two secrets are generated by pairing (and replaced by the rotation button). Their plaintext
 *     never reaches this page - only fingerprints do - and the manual fallback is `occ config:app:set`,
 *     which is encrypted at rest exactly like a paired secret.
 *
 * Current values are rendered server-side into the form; saving is done by js/pages-admin.js through the
 * admin-only /api/admin/config, /api/bridge/* and /api/site endpoints.
 *
 * @var array $_
 * @var \OCP\IL10N $l
 */

use OCP\Util;

// the admin bundle is built separately from the app main bundle
Util::addStyle('pages', 'pages-admin');
Util::addScript('pages', 'pages-admin');

$health = $_['health'] ?? null;
$error = $_['health_error'] ?? null;
$connected = (bool)$_['connected'];
// single-site design: this section edits the one site of this Nextcloud instance
$site = is_array($_['site'] ?? null) ? $_['site'] : [];
$version = (string)($health['version'] ?? '');
// the read-only summary: the two counts the page reports without owning them
$externalCount = $_['external_count'] ?? null;
$unsynced = is_array($_['unsynced'] ?? null) ? $_['unsynced'] : ['added' => 0, 'removed' => 0, 'errors' => []];
?>
<div class="section" id="pages-settings">
	<h2>Pages</h2>
	<p class="settings-hint">
		<?php p($l->t('Edit static site sources in Nextcloud; after saving, pages-bridge on the host mirrors, builds and pushes them to the git remote.')); ?>
	</p>

	<h3><?php p($l->t('pages-bridge')); ?></h3>

	<?php // the state comes from the server, so the panel is right on first paint (no flash of the wrong form) ?>
	<div id="pages-bridge-panel" data-paired="<?php p($connected ? '1' : '0'); ?>"
		data-revision="<?php p((string)$_['revision']); ?>"
		data-pushed-revision="<?php p((string)$_['pushed_revision']); ?>">
		<p>
			<label for="pages-bridge-url"><?php p($l->t('URL')); ?></label><br />
			<input type="text" id="pages-bridge-url" placeholder="http://127.0.0.1:8787"
				value="<?php p($_['bridge_url']); ?>" style="width: 320px;" />
		</p>

		<?php if (!$connected): ?>
			<p id="pages-pair-row">
				<label for="pages-pair-code"><?php p($l->t('Pairing code')); ?></label><br />
				<input type="text" id="pages-pair-code" autocomplete="off" placeholder="XXXXXXXX" style="width: 160px;" />
				<button type="button" id="pages-pair" class="primary"><?php p($l->t('Pair')); ?></button>
			</p>
			<p class="settings-hint">
				<?php p($l->t('Run `sudo bridge/install.sh` on the Nextcloud host: it prints the pairing code (valid for 10 minutes, 3 tries). Hosted pairing only works when the bridge runs on the same machine.')); ?>
			</p>
			<p class="settings-hint" id="pages-pair-note">
				<?php p($l->t('Pairing generates both secrets here, discovers the Nextcloud data directory and hands both to the bridge. The global bridge parameters are sent along as they are set.')); ?>
			</p>
		<?php else: ?>
			<p class="settings-hint" id="pages-bridge-status">
				<?php
                // "Connected · protocol v3 · bridge 1.3.0" — the same three facts the status table shows
                $parts = [$l->t('Connected'), $l->t('protocol v') . $_['protocol']];
		        if ($version !== '') {
		            $parts[] = $l->t('bridge') . ' ' . $version;
		        }
		        p(implode(' · ', $parts));
		        ?>
			</p>
			<p>
				<button type="button" id="pages-save" class="primary"><?php p($l->t('Save and push')); ?></button>
				<button type="button" id="pages-rotate"><?php p($l->t('Rotate secrets')); ?></button>
				<button type="button" id="pages-pair-again"><?php p($l->t('Pair again')); ?></button>
			</p>
			<p class="settings-hint" id="pages-restart-note" hidden></p>
		<?php endif; ?>

		<?php // one feedback line for both states: pairing and pushing report through the same element ?>
		<p><span id="pages-feedback" class="pages-feedback" role="status" aria-live="polite"></span></p>

		<p class="settings-hint" id="pages-fingerprints">
			<?php p($l->t('Shared secret') . ' ' . ($_['shared_fingerprint'] !== '' ? $_['shared_fingerprint'] : $l->t('(not configured)'))); ?>
			·
			<?php p($l->t('Signing secret') . ' ' . ($_['signing_fingerprint'] !== '' ? $_['signing_fingerprint'] : $l->t('(not configured)'))); ?>
			<br />
			<?php p($l->t('The app generates both secrets while pairing and stores them encrypted; only fingerprints are ever shown here. The manual fallback is `occ config:app:set`.')); ?>
		</p>
	</div>

	<h3><?php p($l->t('Status')); ?></h3>
	<?php // read only on purpose: the two counts are derived (manifest / author folders), not settings ?>
	<table class="pages-info" id="pages-status">
		<tbody>
		<tr>
			<td><?php p($l->t('Connection')); ?></td>
			<td>
				<?php if (!$connected): ?>
					<span class="pages-badge warn"><?php p($l->t('Not configured')); ?></span>
				<?php elseif ($error !== null): ?>
					<span class="pages-badge error"><?php p($l->t('Unreachable')); ?></span>
					<code><?php p(($error['code'] ?? '') . ' — ' . ($error['message'] ?? '')); ?></code>
					<?php if (($error['retryable'] ?? false) === true): ?>
						<span class="settings-hint"><?php p($l->t('The service did not answer, so nothing was changed: start it and reload this page.')); ?></span>
					<?php endif; ?>
				<?php else: ?>
					<span class="pages-badge ok"><?php p($l->t('Connected')); ?></span>
					<?php p(trim(($health['service'] ?? '') . ' ' . ($health['version'] ?? ''))); ?>
				<?php endif; ?>
			</td>
		</tr>
		<tr>
			<td><?php p($l->t('Protocol version')); ?></td>
			<td>
				<?php p($l->t('App requires v') . $_['protocol']); ?>
				<?php if ($health !== null): ?>
					· <?php p($l->t('bridge reports v') . ($health['protocol'] ?? '?')); ?>
					<?php if ((int)($health['protocol'] ?? 0) !== (int)$_['protocol']): ?>
						<span class="pages-badge error"><?php p($l->t('Mismatch')); ?></span>
					<?php endif; ?>
				<?php endif; ?>
			</td>
		</tr>
		<tr>
			<td><?php p($l->t('Config revision')); ?></td>
			<td>
				<code><?php p((string)$_['revision']); ?></code>
				<?php // the third state is decided by the script, from the saved values and /env; the
				// two revision-based states are already known here and stay rendered server-side ?>
				<span class="pages-badge ok" id="pages-sync-state"
					data-revision="<?php p((string)$_['revision']); ?>"
					data-pushed-revision="<?php p((string)$_['pushed_revision']); ?>"
					data-has-unpushed="<?php p($_['has_unpushed'] ? '1' : '0'); ?>"><?php
					if ($_['has_unpushed']) {
					    p($l->t('Changes not pushed to the bridge'));
					} else {
					    p($l->t('In sync'));
					}
					?></span>
			</td>
		</tr>
		<tr>
			<td><?php p($l->t('Approved for the site')); ?></td>
			<td>
				<code id="pages-external-count"><?php p($externalCount === null ? $l->t('(unknown)') : (string)$externalCount); ?></code>
				<span class="settings-hint"><?php p($l->t('Articles the visibility manifest holds as approved for the site, whether or not a publish has carried them yet.')); ?></span>
			</td>
		</tr>
		<tr>
			<td><?php p($l->t('Not yet on the bridge')); ?></td>
			<td>
				<?php // added / removed are computed from the author folders against the last accepted push ?>
				<code id="pages-unsynced-count"><?php p($l->t('%1$s new or changed · %2$s to remove', [
				    (string)($unsynced['added'] ?? 0),
				    (string)($unsynced['removed'] ?? 0),
				])); ?></code>
				<?php if (($unsynced['errors'] ?? []) !== []): ?>
					<span class="pages-badge warn"><?php p($l->t('unreadable: %s', [implode(', ', array_map('strval', $unsynced['errors']))])); ?></span>
				<?php endif; ?>
				<span class="settings-hint"><?php p($l->t('A file the bridge has not received yet: saving it again, or the retry mark on the entry, pushes the author folder.')); ?></span>
			</td>
		</tr>
		</tbody>
	</table>

	<h3><?php p($l->t('Site')); ?></h3>
	<?php // no site id and no name any more: the title is basename(nc_path), derived by the backend ?>
	<p>
		<label for="pages-site-nc-user"><?php p($l->t('Site storage user')); ?></label><br />
		<?php // data-current is what the script compares against: a change here starts the §14 flow ?>
		<input type="text" id="pages-site-nc-user" placeholder="<?php p((string)($_['nc_user'] ?? '')); ?>"
			data-current="<?php p((string)($site['nc_user'] ?? '')); ?>"
			value="<?php p($site['nc_user'] ?? ''); ?>" style="width: 200px;" />
		<?php // the store user is an instance-level setting now; this hint is the string that already exists ?>
		<span class="settings-hint"><?php p($l->t('Which user owns the folder; this app is used single-user, so an empty value means the current user.')); ?></span>
	</p>
	<p>
		<label for="pages-site-nc-path"><?php p($l->t('Nextcloud folder (source of truth)')); ?></label><br />
		<input type="text" id="pages-site-nc-path" placeholder="/Sites/my-site"
			value="<?php p($site['nc_path'] ?? ''); ?>" style="width: 320px;" />
	</p>
	<p>
		<label for="pages-site-repo"><?php p($l->t('Git remote (GitHub repository)')); ?></label><br />
		<input type="text" id="pages-site-repo" placeholder="git@github.com:user/repo.git"
			value="<?php p($site['repo_url'] ?? ''); ?>" style="width: 420px;" />
	</p>
	<p>
		<label for="pages-site-branch"><?php p($l->t('Branch')); ?></label><br />
		<input type="text" id="pages-site-branch" placeholder="main"
			value="<?php p($site['branch'] ?? 'main'); ?>" style="width: 160px;" />
	</p>
	<p class="settings-hint">
		<?php p($l->t('The build command, the output folder and the site-level exclusions duplicate the bridge\'s own configuration ([site.recipe] and exclude/unexclude in its TOML, `occ pages:config` for the global list), so they are not edited here: the stored values are kept and "Save site" does not reset them.')); ?>
	</p>

	<p>
		<button type="button" id="pages-site-save" class="primary"><?php p($l->t('Save site')); ?></button>
		<button type="button" id="pages-site-init"><?php p($l->t('Initialise working copy (first git pull)')); ?></button>
		<button type="button" id="pages-site-pull"><?php p($l->t('Pull from remote')); ?></button>
		<span id="pages-site-feedback" class="pages-feedback" role="status" aria-live="polite"></span>
	</p>

	<?php
    // §14: the choice between moving the site folder and rebuilding it from git. The markup lives in an
    // inert <template>: its radio group is only a live control while a migration is really pending, which
    // is why the page itself carries no migration input (the script clones this content into the
    // container below when a preflight says the new location is missing or empty).
    ?>
	<div id="pages-site-migration" hidden></div>
	<template id="pages-site-migration-template">
		<p class="settings-hint">
			<?php p($l->t('The new location is missing or empty. Choose how to fill it; nothing happens until you continue.')); ?>
		</p>
		<p class="settings-hint" data-migration="warnings" hidden></p>
		<p>
			<label><input type="radio" name="pages-site-migration-mode" value="migrate" checked />
				<?php p($l->t('Migrate the site folder (recommended)')); ?></label><br />
			<label><input type="radio" name="pages-site-migration-mode" value="git" />
				<?php p($l->t('Do not migrate, rebuild from git')); ?></label>
		</p>
		<p class="settings-hint">
			<?php p($l->t('Migrating copies the folder through Nextcloud (the copy is verified before the old one is removed). Rebuilding instead saves the new user and leaves the working copy empty until you initialise it.')); ?>
		</p>
		<p>
			<button type="button" data-migration="start" class="primary"><?php p($l->t('Continue')); ?></button>
			<button type="button" data-migration="cancel"><?php p($l->t('Cancel')); ?></button>
		</p>
		<p class="settings-hint" data-migration="steps" hidden></p>
	</template>

	<?php
    // Authoring: every participating user writes into their own `Pages/` folder, whose whole tree the
    // app mirrors into the one site under `<author content directory>/<user>/`. The directory is one
    // site-relative path segment, never empty (default `tmp`).
    // *Who* may author is a group grant, and it is handed out in the Permissions matrix below.
    $authorRoot = (string)($_['author_root'] ?? 'tmp');
    ?>
	<h3><?php p($l->t('Authors')); ?></h3>
	<p class="settings-hint">
		<?php p($l->t('Everyone with the authoring grant writes into the Pages folder of their own files. The site receives everything in it under <content directory>/<user>/, and every file — pages and images alike — has to pass review before the site serves it.')); ?>
	</p>
	<div id="pages-authors">
		<p>
			<label for="pages-author-root"><?php p($l->t('Author content directory')); ?></label><br />
			<input type="text" id="pages-author-root" value="<?php p($authorRoot); ?>"
				placeholder="tmp" style="width: 320px;" />
			<span class="settings-hint"><?php p($l->t('One folder name inside the site (letters, digits, dot, underscore, hyphen), never empty. Default: tmp.')); ?></span>
		</p>
	</div>

	<?php
    // Two capabilities, each a group list; administrators always hold both, and the preview needs no
    // grant at all (every signed-in user may open it). Reviewing and publishing are ONE permission
    // since the merge (审核与发布): deciding about a request and pushing the commit are the same job,
    // so there is one picker for both - the retired publish grant is merged into it by the migration
    // and is not shown any more.
    $authorGroups = array_map('strval', is_array($_['author_groups'] ?? null) ? $_['author_groups'] : []);
    $reviewGroups = array_map('strval', is_array($_['review_groups'] ?? null) ? $_['review_groups'] : []);
    $allGroups = is_array($_['all_groups'] ?? null) ? $_['all_groups'] : [];
    // One option list for the two pickers; an entry without an id cannot be granted, so it is dropped
    $grantOptions = [];
    foreach ($allGroups as $group) {
        $gid = (string)($group['id'] ?? '');
        if ($gid === '') {
            continue;
        }
        $grantOptions[] = ['id' => $gid, 'displayName' => (string)($group['displayName'] ?? $gid)];
    }
    ?>
	<h3><?php p($l->t('Permissions')); ?></h3>
	<p class="settings-hint"><?php p($l->t('Administrators always have full access. Grant more here.')); ?></p>
	<p class="settings-hint"><?php p($l->t('All signed-in users can view the preview.')); ?></p>
	<div id="pages-permissions">
		<?php
        // One picker per capability, rendered by src/GrantPicker.vue into the container below. An
        // empty list keeps the documented default: authoring is open to every signed-in user, the
        // review-and-publish grant stays with the administrators alone — which is why the default is
        // the picker's placeholder and not an option in the list. The label of the second one says
        // that it covers publishing, because it does: there is no separate publish picker any more.
        $grants = [
            ['pages-author-groups', $l->t('Author'), $authorGroups, $l->t('every signed-in user')],
            ['pages-review-groups', $l->t('Review and publish'), $reviewGroups, $l->t('administrators only')],
        ];
        $grantState = ['options' => $grantOptions, 'grants' => []];
        foreach ($grants as [$grantId, $grantLabel, $grantValue, $emptyLabel]) {
            $grantState['grants'][] = [
                'id' => $grantId,
                'label' => $grantLabel,
                'placeholder' => $emptyLabel,
                'value' => array_values($grantValue),
            ];
        }
        // the pickers start from this; JSON_HEX_* keeps a group name from closing the script tag
        $grantJson = json_encode($grantState, JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT | JSON_UNESCAPED_UNICODE);
        if ($grantJson === false) {
            $grantJson = '{"options":[],"grants":[]}';
        }
        ?>
		<div id="pages-grants"></div>
		<?php // The values, in the inputs the plain save path reads (src/admin.js). They are rendered
		      // by the server, so a bundle whose pickers never mount still saves what is stored now. ?>
		<?php foreach ($grantState['grants'] as $grant): ?>
			<?php $grantInputValue = json_encode($grant['value'], JSON_UNESCAPED_UNICODE); ?>
			<input type="hidden" class="pages-grant-value" id="<?php p((string)$grant['id']); ?>"
				value="<?php p(is_string($grantInputValue) ? $grantInputValue : '[]'); ?>" />
		<?php endforeach; ?>
		<script type="application/json" id="pages-grants-state"><?php print_unescaped($grantJson); ?></script>
		<p class="settings-hint"><?php p($l->t('Each capability is independent. Search for a group and select as many as the capability should have; remove a tag to take that grant away.')); ?></p>
		<p class="settings-hint"><?php p($l->t('“Review and publish” is one permission: deciding about a visibility request and pushing the commit are the same job.')); ?></p>
		<p class="settings-hint"><?php p($l->t('Administrators always have full access.')); ?></p>
	</div>
</div>
